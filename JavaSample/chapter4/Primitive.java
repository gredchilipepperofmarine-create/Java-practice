public class Primitive {
  public static void main (String[] args) {
    byte a = 100;
    short b = 1000;
    int c = 100_000_000;
    long d = 100_000_000L;
    long e = 100_000_000_000L;

    System.out.println(a);
    System.out.println(b);
    System.out.println(c);
    System.out.println(d);
    System.out.println(e);
    
  }
  
}
